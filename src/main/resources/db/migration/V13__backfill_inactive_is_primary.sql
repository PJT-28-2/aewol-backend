-- V13: 연동 해제된(INACTIVE) 계좌에 남아있는 is_primary=1 보정 (2026-08-07)
--
-- 원래 V9로 작성했으나, develop에 이미 V9~V11이 존재하고 fix/#43이 V12를
-- 사용해서 번호 충돌 방지를 위해 V13으로 재번호를 매겼다(2026-08-08). 이
-- 파일은 로컬/PR 단계에서만 존재했고 운영·개발 DB에 V9로 적용된 적은 없다.
--
-- 대표 계좌 설정 API(#46) 추가 전에는 계좌 연동 해제(DELETE) 시 is_primary를
-- 같이 내리지 않았다 — 그래서 대표 계좌였던 상태로 연동 해제된 행은 INACTIVE로
-- 바뀐 뒤에도 is_primary=1이 그대로 남아있을 수 있다. 목록/대표 지정 쿼리는
-- status='ACTIVE'만 보기 때문에 화면에는 문제가 없었지만, 데이터 정합성을
-- 맞추기 위해 기존 데이터를 일괄 보정한다(CodeRabbit 지적, 2026-08-07).
-- =====================================================================

UPDATE `linked_account` SET `is_primary` = 0 WHERE `status` = 'INACTIVE' AND `is_primary` = 1;
