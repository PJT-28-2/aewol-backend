-- V45: 공개 사진 사본 키 저장
--
-- 일기 사진은 평소 만료되는 서명 URL로 나간다. 멍스타그램 피드에는 그 방식을 쓸 수 없어
-- (만료되면 깨지고 CDN 캐싱도 어렵다) 공개로 전환할 때만 사본을 따로 만들어 CDN이 그대로
-- 서빙하는 자리에 둔다. 그 사본의 키를 여기 적어 둔다.
--
-- 원본(image_url)은 손대지 않는다. 공개본은 파생물이고, 비공개로 되돌리면 공개본만 지운다.
--
-- 값이 있으면 "이 사진은 지금 공개 사본이 있다"는 뜻이다. 비공개 전환 시 NULL로 되돌린다.

ALTER TABLE `care_diary_image`
    ADD COLUMN `public_image_key` VARCHAR(500) NULL
        COMMENT '공개 사본 키. 공개 중일 때만 값이 있다' AFTER `image_url`;
