-- V16: FAQ 샘플 데이터 시드
--
-- 원래 V14로 작성했으나, 지연/대구님이 각자 작업 중인 마이그레이션이 이미 V14/V15를
-- 쓰고 있어(팀 채팅 확인, 2026-08-08) 번호가 겹쳐 V16으로 조정했다. 아직 develop에
-- merge되지 않은 로컬 전용 파일이라 번호를 바꿔도 실제 적용 이력에 영향 없음.
--
-- faq 테이블은 V1에서 만들어진 뒤 지금까지 시드 데이터가 없어 FAQ 목록/상세 API를
-- Postman 등으로 테스트하려 해도 빈 배열만 반환됐다. category는 InquiryServiceImpl의
-- ALLOWED_CATEGORIES(api_명세서.md: "category는 FAQ와 동일한 값 사용")와 동일하게
-- 맞춘다: 지갑·버킷 / 보험 / 계좌연동 / 공동양육 / 회원정보 / 기타.
--
-- 이미 시드가 들어간 뒤 재실행(예: 로컬 DB 재생성 없이 마이그레이션만 다시 돌리는 경우)
-- 되더라도 중복 삽입되지 않도록 question 기준 존재 여부를 확인한다.

INSERT INTO `faq` (`category`, `question`, `answer`)
SELECT seed.`category`, seed.`question`, seed.`answer`
FROM (
    SELECT '계좌연동' AS `category`,
           '1원 인증은 어떻게 진행하나요?' AS `question`,
           '연동할 계좌의 은행과 계좌번호를 입력하면 1원이 입금되고, 입금 시 통장에 표시되는 4자리 인증코드를 앱에 입력하면 계좌 연동이 완료돼요. 인증코드는 발급 후 일정 시간이 지나면 만료되며, 여러 번 틀리면 다시 인증을 요청해야 해요.' AS `answer`
    UNION ALL SELECT
        '계좌연동', '대표 계좌는 무엇이고 어떻게 바꾸나요?',
        '대표 계좌는 자동이체·정산 등에 기본으로 사용되는 계좌예요. 연동 계좌 목록에서 다른 계좌를 대표 계좌로 설정하면 기존 대표 계좌는 자동으로 해제돼요.'
    UNION ALL SELECT
        '계좌연동', '연동한 계좌를 해제하면 버킷의 잔액은 어떻게 되나요?',
        '계좌 연동을 해제해도 애월 지갑과 버킷에 쌓인 금액은 그대로 유지돼요. 다만 해당 계좌를 통한 자동이체·충전은 더 이상 이용할 수 없어요.'
    UNION ALL SELECT
        '지갑·버킷', '버킷은 몇 개까지 만들 수 있나요?',
        '반려동물 한 마리당 버킷 개수 제한은 없어요. 사료비, 병원비, 미용비처럼 목적별로 자유롭게 나눠 만들어서 관리할 수 있어요.'
    UNION ALL SELECT
        '지갑·버킷', 'SOS 포켓은 무엇인가요?',
        'SOS 포켓은 갑작스러운 병원비 등 긴급 상황을 위해 따로 모아두는 비상금 버킷이에요. 일반 버킷과 분리해서 관리되며 목표 금액을 설정할 수 있어요.'
    UNION ALL SELECT
        '보험', '보험료 시뮬레이션은 실제 가입 견적과 같나요?',
        '시뮬레이션은 반려동물의 나이, 품종, 보장 범위 등을 바탕으로 한 예상 금액이에요. 실제 가입 심사 결과에 따라 보험사가 제시하는 최종 보험료는 달라질 수 있어요.'
    UNION ALL SELECT
        '보험', '보험금 청구 서류는 어떻게 준비하나요?',
        '진료비 영수증을 촬영해서 업로드하면 OCR로 항목을 자동 인식해 청구 서류 작성을 도와드려요. 인식이 정확한지 제출 전에 꼭 확인해 주세요.'
    UNION ALL SELECT
        '공동양육', '공동 양육자를 초대하려면 어떻게 하나요?',
        '반려동물 상세 화면에서 공동 양육자 초대 메뉴를 통해 이메일이나 초대 링크로 함께 관리할 보호자를 초대할 수 있어요. 초대받은 보호자는 권한 범위 내에서 지출 내역과 버킷을 함께 확인할 수 있어요.'
    UNION ALL SELECT
        '공동양육', '공동 양육자마다 권한을 다르게 줄 수 있나요?',
        '네, 조회만 가능한 권한과 지출·버킷 관리까지 가능한 권한을 구분해서 설정할 수 있어요.'
    UNION ALL SELECT
        '회원정보', '카카오 계정으로 가입했는데 비밀번호로도 로그인할 수 있나요?',
        '카카오 등 소셜 계정으로 가입한 경우 이메일/비밀번호 로그인은 지원되지 않아요. 항상 가입 시 사용한 소셜 계정으로 로그인해 주세요.'
    UNION ALL SELECT
        '회원정보', '회원 탈퇴하면 지출 내역도 모두 삭제되나요?',
        '탈퇴 시 개인 식별 정보는 삭제되지만, 통계·정산 목적의 최소한의 거래 기록은 관련 법령에 따라 일정 기간 보관될 수 있어요.'
    UNION ALL SELECT
        '기타', '앱에서 오류가 발생하면 어디로 문의하면 되나요?',
        '고객센터의 1:1 문의를 통해 오류 상황과 재현 방법을 알려주시면 확인 후 답변드려요. 스크린샷을 함께 첨부해 주시면 더 빠르게 확인할 수 있어요.'
) seed
WHERE NOT EXISTS (
    SELECT 1 FROM `faq` existing WHERE existing.`question` = seed.`question`
);
