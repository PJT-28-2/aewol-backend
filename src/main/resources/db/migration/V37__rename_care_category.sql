-- V37: 문의/FAQ 카테고리 '공동양육'을 '공동육아'로 변경
--
-- 화면 문구에서 "공동양육"과 "공동육아"가 섞여 있어 팀에서 "공동육아"로 통일하기로
-- 정했다(2026-08-19 회의). 문구는 프론트에서 바꾸면 되지만 category는 값 자체가
-- DB·서버 상수·프론트 상수 세 곳에 문자열로 맞물려 있어 함께 움직여야 한다.
--
-- V16이 넣은 시드를 직접 고치지 않고 새 버전으로 갱신한다. V16은 이미 적용된
-- 마이그레이션이라 내용을 바꾸면 checksum이 어긋나 Flyway가 기동을 막는다.
--
-- inquiry.category는 사용자가 작성한 문의에 붙는 값이라 운영 데이터가 있을 수 있어
-- 함께 갱신한다. 갱신하지 않으면 기존 문의가 ALLOWED_CATEGORIES 검증을 통과하지
-- 못하는 값을 들고 남는다.

UPDATE `faq`
SET `category` = '공동육아'
WHERE `category` = '공동양육';

UPDATE `inquiry`
SET `category` = '공동육아'
WHERE `category` = '공동양육';
